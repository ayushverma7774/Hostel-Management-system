-- 2. HOSTEL TABLE

CREATE TABLE Hostel (
    hostel_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(100) NOT NULL,
    address VARCHAR2(255) NOT NULL,
    gender_type VARCHAR2(20) NOT NULL
);

-- 3. ROOM_TYPE TABLE

CREATE TABLE Room_Type (
    type_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_name VARCHAR2(50) NOT NULL,
    description VARCHAR2(255)
);

-- 4. WARDEN TABLE

CREATE TABLE Warden (
    warden_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hostel_id NUMBER NOT NULL UNIQUE,
    name VARCHAR2(100) NOT NULL,
    phone VARCHAR2(15),
    email VARCHAR2(100),
    department VARCHAR2(100),

    CONSTRAINT fk_warden_hostel
    FOREIGN KEY (hostel_id)
    REFERENCES Hostel(hostel_id)
    ON DELETE CASCADE
);

-- 5. ROOM TABLE

CREATE TABLE Room (
    room_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hostel_id NUMBER NOT NULL,
    type_id NUMBER NOT NULL,
    room_no VARCHAR2(20) NOT NULL,
    capacity NUMBER NOT NULL CHECK (capacity > 0),
    monthly_rent NUMBER(10,2) NOT NULL CHECK (monthly_rent >= 0),

    CONSTRAINT uq_hostel_room UNIQUE (hostel_id, room_no),

    CONSTRAINT fk_room_hostel
    FOREIGN KEY (hostel_id)
    REFERENCES Hostel(hostel_id)
    ON DELETE CASCADE,

    CONSTRAINT fk_room_type
    FOREIGN KEY (type_id)
    REFERENCES Room_Type(type_id)
);

-- 6. STUDENT TABLE

CREATE TABLE Student (
    student_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id NUMBER NOT NULL,
    firstname VARCHAR2(50) NOT NULL,
    lastname VARCHAR2(50) NOT NULL,
    email VARCHAR2(100) UNIQUE,
    phone VARCHAR2(15),
    gender VARCHAR2(20),

    CONSTRAINT fk_student_room
    FOREIGN KEY (room_id)
    REFERENCES Room(room_id)
);

-- 7. FEE_PAYMENT TABLE

CREATE TABLE Fee_Payment (
    payment_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id NUMBER NOT NULL,
    amount NUMBER(10,2) NOT NULL CHECK (amount > 0),
    payment_mode VARCHAR2(30) NOT NULL,
    payment_date DATE NOT NULL,

    CONSTRAINT fk_payment_student
    FOREIGN KEY (student_id)
    REFERENCES Student(student_id)
);

