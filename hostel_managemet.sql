-- =========================================
-- JOIN: HOSTEL + ROOM + STUDENT
-- =========================================

SELECT
    h.hostel_id,
    h.name AS hostel_name,
    r.room_no,
    rt.type_name,
    r.monthly_rent,
    s.student_id,
    s.firstname,
    s.lastname
FROM Hostel h
JOIN Room r ON h.hostel_id = r.hostel_id
JOIN Room_Type rt ON r.type_id = rt.type_id
LEFT JOIN Student s ON r.room_id = s.room_id;

-- =========================================
-- JOIN: STUDENT + FEE PAYMENT
-- =========================================

SELECT
    s.student_id,
    s.firstname,
    s.lastname,
    f.payment_id,
    f.amount,
    f.payment_mode,
    f.payment_date
FROM Student s
JOIN Fee_Payment f ON s.student_id = f.student_id;
